create or replace function public.ms_ensure_wallet() returns void language plpgsql security definer set search_path='' as $$
begin if auth.uid() is null then raise exception 'Not authenticated'; end if;
insert into public.ms_virtual_wallets(user_id) values(auth.uid()) on conflict do nothing; end $$;

create or replace function public.ms_get_referral_code() returns text language plpgsql security definer set search_path='' as $$
declare c text; begin if auth.uid() is null then raise exception 'Not authenticated'; end if;
select referral_code into c from public.ms_referral_codes where user_id=auth.uid();
if c is null then c='MS'||upper(substr(replace(auth.uid()::text,'-',''),1,8)); insert into public.ms_referral_codes(user_id,referral_code) values(auth.uid(),c) on conflict do nothing; end if; return c; end $$;

create or replace function public.ms_activate_package(p_package_id bigint) returns bigint language plpgsql security definer set search_path='' as $$
declare price numeric; bal numeric; cid bigint; begin if auth.uid() is null then raise exception 'Not authenticated'; end if; perform public.ms_ensure_wallet();
select price_myc into price from public.ms_virtual_packages where id=p_package_id and active=true and duration_days=30;
if price is null then raise exception 'Package tidak ditemukan'; end if;
update public.ms_virtual_wallets set balance_myc=balance_myc-price,lifetime_spent_myc=lifetime_spent_myc+price,updated_at=now()
where user_id=auth.uid() and balance_myc>=price returning balance_myc into bal;
if bal is null then raise exception 'Saldo MYC virtual tidak cukup'; end if;
insert into public.ms_mining_contracts(user_id,package_id,started_at,ends_at) values(auth.uid(),p_package_id,now(),now()+interval '30 days') returning id into cid;
insert into public.ms_virtual_transactions(user_id,tx_type,amount_myc,balance_after_myc,reference_id,description) values(auth.uid(),'package_activation',-price,bal,cid::text,'Aktivasi paket mining virtual 30 hari'); return cid; end $$;

create or replace function public.ms_claim_mining(p_contract_id bigint) returns numeric language plpgsql security definer set search_path='' as $$
declare power integer; ending timestamptz; lastc timestamptz; reward numeric; bal numeric; st text; begin
if auth.uid() is null then raise exception 'Not authenticated'; end if; perform public.ms_ensure_wallet();
select p.mining_power,c.ends_at,c.last_claim_at,c.status into power,ending,lastc,st from public.ms_mining_contracts c join public.ms_virtual_packages p on p.id=c.package_id where c.id=p_contract_id and c.user_id=auth.uid() for update;
if power is null then raise exception 'Contract tidak ditemukan'; end if; if st<>'active' then raise exception 'Contract tidak aktif'; end if;
reward=round(greatest(0,extract(epoch from(least(now(),ending)-lastc))/3600.0)*power*0.02,4);
if reward<=0 then return 0; end if;
update public.ms_mining_contracts set last_claim_at=least(now(),ending),total_mined_myc=total_mined_myc+reward,status=case when now()>=ending then 'completed' else 'active' end where id=p_contract_id;
update public.ms_virtual_wallets set balance_myc=balance_myc+reward,lifetime_earned_myc=lifetime_earned_myc+reward,updated_at=now() where user_id=auth.uid() returning balance_myc into bal;
insert into public.ms_virtual_transactions(user_id,tx_type,amount_myc,balance_after_myc,reference_id,description) values(auth.uid(),'mining_reward',reward,bal,p_contract_id::text,'Reward mining virtual'); return reward; end $$;

revoke execute on function public.ms_ensure_wallet() from public,anon;
revoke execute on function public.ms_get_referral_code() from public,anon;
revoke execute on function public.ms_activate_package(bigint) from public,anon;
revoke execute on function public.ms_claim_mining(bigint) from public,anon;
grant execute on function public.ms_ensure_wallet() to authenticated;
grant execute on function public.ms_get_referral_code() to authenticated;
grant execute on function public.ms_activate_package(bigint) to authenticated;
grant execute on function public.ms_claim_mining(bigint) to authenticated;
