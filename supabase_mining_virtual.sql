-- SAFE VIRTUAL REWARD MODEL
-- MYC = virtual/non-cashable points. Do not connect this to cash deposits or fixed financial returns.

create table if not exists public.ms_virtual_packages(
 id bigint generated by default as identity primary key, code text unique not null,
 name text not null, price_myc numeric(18,4) not null check(price_myc>0),
 mining_power integer not null check(mining_power>0), duration_days integer not null default 30 check(duration_days=30), active boolean not null default true);

create table if not exists public.ms_virtual_wallets(
 user_id uuid primary key references auth.users(id) on delete cascade,
 balance_myc numeric(18,4) not null default 0 check(balance_myc>=0),
 lifetime_earned_myc numeric(18,4) not null default 0,
 lifetime_spent_myc numeric(18,4) not null default 0, created_at timestamptz default now(), updated_at timestamptz default now());

create table if not exists public.ms_mining_contracts(
 id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade,
 package_id bigint not null references public.ms_virtual_packages(id), started_at timestamptz default now(),
 ends_at timestamptz not null, last_claim_at timestamptz default now(), total_mined_myc numeric(18,4) default 0,
 status text default 'active' check(status in('active','completed','cancelled')));

create table if not exists public.ms_virtual_transactions(
 id bigint generated by default as identity primary key,user_id uuid not null references auth.users(id) on delete cascade,
 tx_type text not null,amount_myc numeric(18,4) not null,balance_after_myc numeric(18,4) not null,
 reference_id text,description text not null,created_at timestamptz default now());

create table if not exists public.ms_referral_codes(user_id uuid primary key references auth.users(id) on delete cascade,referral_code text unique not null,created_at timestamptz default now());
create table if not exists public.ms_referrals(id bigint generated by default as identity primary key,referrer_id uuid not null references auth.users(id) on delete cascade,referred_id uuid unique not null references auth.users(id) on delete cascade,referral_code text not null,verified_at timestamptz,qualifying_missions integer default 0,created_at timestamptz default now(),check(referrer_id<>referred_id));

